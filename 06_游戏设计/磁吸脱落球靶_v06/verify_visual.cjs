const {chromium}=require('C:/Users/白/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright');
const {pathToFileURL}=require('url');
const path=require('path');
const fs=require('fs');
(async()=>{
 const browser=await chromium.launch({headless:true,channel:'msedge'});
 const page=await browser.newPage({viewport:{width:1480,height:1120},deviceScaleFactor:1});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto(pathToFileURL(path.join(__dirname,'index.html')).href);
 await page.screenshot({path:path.join(__dirname,'preview.png'),fullPage:true});
 await page.locator('.scenes').screenshot({path:path.join(__dirname,'states.png')});
 await page.getByRole('button',{name:'蓝靶',exact:true}).click();
 const blue=await page.evaluate(()=>getComputedStyle(document.documentElement).getPropertyValue('--ball'));
 if(blue.trim()!=='#3c8dde')throw Error('Blue toggle failed');
 await page.getByRole('button',{name:'命中后',exact:true}).click();
 if(await page.locator('#ready').isVisible()||!(await page.locator('#hit').isVisible()))throw Error('Hit state visibility failed');
 await page.getByRole('button',{name:'待击',exact:true}).click();
 if(!(await page.locator('#ready').isVisible())||await page.locator('#hit').isVisible())throw Error('Ready state visibility failed');
 await page.getByRole('button',{name:'两态对照',exact:true}).click();
 await page.setViewportSize({width:390,height:844});
 const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>window.innerWidth+1);
 await page.screenshot({path:path.join(__dirname,'preview_mobile.png'),fullPage:true});
 await page.setViewportSize({width:1440,height:1250});
 await page.setContent('<html><body style="margin:0">'+fs.readFileSync(path.join(__dirname,'target_detail.svg'),'utf8')+'</body></html>');
 await page.screenshot({path:path.join(__dirname,'target_detail.png'),fullPage:true});
 const checks={javascript_errors:errors,blue_toggle:blue.trim(),state_toggles:'pass',mobile_horizontal_overflow:overflow,standalone_svg:'rendered'};
 fs.writeFileSync(path.join(__dirname,'visual_checks.json'),JSON.stringify(checks,null,2));
 console.log(JSON.stringify(checks));await browser.close();
 if(errors.length||overflow)process.exitCode=1;
})();
